//! Generate VS Code artifacts from the model (`JsonSchema`) and vocabulary.
//!
//! Outputs: JSON Schema (schemars from model), dsl-surface, keyword docs, TextMate,
//! and human-readable `docs/generated/dsl-vocabulary.md`.

use std::collections::BTreeMap;
use std::env;
use std::fs;
use std::path::{Path, PathBuf};

use codemod_recipe_yaml::{
    dsl_surface_json, keyword_docs_json, map_schema, recipe_schema, syntax_alternation,
    variables_schema, KeywordDocJson, SyntaxGroup,
};
use serde_json::Value;

fn repo_root() -> PathBuf {
    PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("../../..")
}

fn vscode_root(repo: &Path) -> PathBuf {
    repo.join("vscode_extension")
}

fn write_json(path: &Path, value: &Value) -> Result<(), String> {
    let json = serde_json::to_string_pretty(value).map_err(|e| e.to_string())?;
    fs::write(path, format!("{json}\n")).map_err(|e| e.to_string())?;
    Ok(())
}

fn write_keyword_docs(out: &Path) -> Result<(), String> {
    let docs = keyword_docs_json();
    let json = serde_json::to_string_pretty(&docs).map_err(|e| e.to_string())?;
    fs::write(out, format!("{json}\n")).map_err(|e| e.to_string())?;
    Ok(())
}

fn escape_md_cell(s: &str) -> String {
    s.replace('|', "\\|").replace('\n', " ")
}

fn kind_section_title(kind: &str) -> &'static str {
    match kind {
        "TopLevelField" => "Recipe top-level fields",
        "AssetRootField" => "Map and variables asset fields",
        "StepKind" => "Step kinds",
        "OpKind" => "Edit op kinds",
        "Field" => "Fields",
        "EnumValue" => "Enum values",
        _ => "Other",
    }
}

fn kind_order(kind: &str) -> u8 {
    match kind {
        "TopLevelField" => 0,
        "AssetRootField" => 1,
        "StepKind" => 2,
        "OpKind" => 3,
        "Field" => 4,
        "EnumValue" => 5,
        _ => 9,
    }
}

/// Group label for a field/enum entry: explicit parent, else schema definition name.
fn entry_group(doc: &KeywordDocJson) -> String {
    if let Some(parent) = &doc.parent {
        return parent.clone();
    }
    if let Some(path) = &doc.schema_path {
        // e.g. "#/definitions/insertOp/properties/capture" → "insertOp"
        // or "map#/properties/id" → "map"
        if let Some(rest) = path.strip_prefix("#/definitions/") {
            if let Some(def) = rest.split('/').next() {
                return def.to_string();
            }
        }
        if let Some((asset, _)) = path.split_once('#') {
            if !asset.is_empty() {
                return asset.to_string();
            }
        }
        if path.starts_with("#/properties/") {
            return "recipeRoot".to_string();
        }
    }
    "(unscoped)".to_string()
}

fn write_vocabulary_md(out: &Path, docs: &[KeywordDocJson], surface: &Value) -> Result<(), String> {
    let mut md = String::new();
    md.push_str("# DSL vocabulary\n\n");
    md.push_str("<!-- Generated by `codemod_dsl_codegen` / `scripts/generate-dsl-artifacts.sh`. Do not edit by hand. -->\n\n");
    md.push_str("Author-facing descriptions for every YAML DSL wire name. Source of truth:\n\n");
    md.push_str("- Structure: `rust/crates/yaml/src/model.rs` (JSON Schema via schemars)\n");
    md.push_str("- Prose: `rust/crates/yaml/src/dsl_vocabulary.rs` (`ENTRIES`)\n\n");
    md.push_str("How to write recipes: [../writing-recipes.md](../writing-recipes.md).\n");
    md.push_str("Day-1 overview: [../getting-started.md](../getting-started.md).\n\n");

    // --- Structural overview from dsl-surface ---
    md.push_str("## Structural overview\n\n");
    md.push_str("Containers and their child fields (from the generated DSL surface):\n\n");

    if let Some(containers) = surface.get("containers").and_then(Value::as_object) {
        for (name, container) in containers {
            let children = container
                .get("children")
                .and_then(Value::as_array)
                .map(|arr| {
                    arr.iter()
                        .filter_map(Value::as_str)
                        .collect::<Vec<_>>()
                        .join(", ")
                })
                .unwrap_or_default();
            let mut flags = Vec::new();
            if container
                .get("mapValue")
                .and_then(Value::as_bool)
                .unwrap_or(false)
            {
                flags.push("map values");
            }
            if container
                .get("scalarAlt")
                .and_then(Value::as_bool)
                .unwrap_or(false)
            {
                flags.push("scalar form allowed");
            }
            let flag_note = if flags.is_empty() {
                String::new()
            } else {
                format!(" _{}_", flags.join("; "))
            };
            if children.is_empty() {
                md.push_str(&format!("- **`{name}`**{flag_note}\n"));
            } else {
                md.push_str(&format!(
                    "- **`{name}`**: `{children}`{flag_note}\n",
                    children = children.replace(", ", "`, `")
                ));
            }
        }
        md.push('\n');
    }

    if let Some(enums) = surface.get("enums").and_then(Value::as_object) {
        md.push_str("### Enums\n\n");
        for (name, values) in enums {
            let list = values
                .as_array()
                .map(|arr| {
                    arr.iter()
                        .filter_map(Value::as_str)
                        .map(|s| format!("`{s}`"))
                        .collect::<Vec<_>>()
                        .join(", ")
                })
                .unwrap_or_default();
            md.push_str(&format!("- **`{name}`**: {list}\n"));
        }
        md.push('\n');
    }

    // --- Vocabulary entries by kind ---
    let mut by_kind: BTreeMap<String, Vec<&KeywordDocJson>> = BTreeMap::new();
    for doc in docs {
        by_kind.entry(doc.kind.clone()).or_default().push(doc);
    }

    let mut kinds: Vec<String> = by_kind.keys().cloned().collect();
    kinds.sort_by_key(|k| kind_order(k));

    for kind in kinds {
        let entries = by_kind.get(&kind).expect("kind present");
        md.push_str(&format!("## {}\n\n", kind_section_title(&kind)));

        if kind == "Field" || kind == "EnumValue" || kind == "AssetRootField" {
            // Group by parent wire or schema definition for scannability
            let mut by_group: BTreeMap<String, Vec<&KeywordDocJson>> = BTreeMap::new();
            for e in entries {
                by_group.entry(entry_group(e)).or_default().push(e);
            }
            for (group_name, group) in by_group {
                md.push_str(&format!("### `{group_name}`\n\n"));
                md.push_str("| Wire | Description |\n");
                md.push_str("|------|-------------|\n");
                for e in group {
                    md.push_str(&format!(
                        "| `{}` | {} |\n",
                        escape_md_cell(&e.wire),
                        escape_md_cell(&e.description)
                    ));
                }
                md.push('\n');
            }
        } else {
            md.push_str("| Wire | Description |\n");
            md.push_str("|------|-------------|\n");
            for e in entries {
                let wire = if let Some(parent) = &e.parent {
                    format!("{parent}.{}", e.wire)
                } else {
                    e.wire.clone()
                };
                md.push_str(&format!(
                    "| `{}` | {} |\n",
                    escape_md_cell(&wire),
                    escape_md_cell(&e.description)
                ));
            }
            md.push('\n');
        }
    }

    fs::create_dir_all(out.parent().unwrap_or(Path::new("."))).map_err(|e| e.to_string())?;
    fs::write(out, md).map_err(|e| e.to_string())?;
    Ok(())
}

fn patch_tm_language_keys(path: &Path) -> Result<(), String> {
    let text = fs::read_to_string(path).map_err(|e| e.to_string())?;
    let mut root: Value = serde_json::from_str(&text).map_err(|e| e.to_string())?;

    let step = syntax_alternation(SyntaxGroup::StepKind);
    let op = syntax_alternation(SyntaxGroup::OpKind);
    let field = syntax_alternation(SyntaxGroup::FieldKey);

    let repo = root
        .get_mut("repository")
        .and_then(Value::as_object_mut)
        .ok_or_else(|| "missing repository".to_string())?;

    for (name, alt) in [
        ("step-kinds", step),
        ("op-kinds", op),
        ("field-keys", field),
    ] {
        let entry = repo
            .get_mut(name)
            .and_then(Value::as_object_mut)
            .ok_or_else(|| format!("missing repository.{name}"))?;
        entry.insert(
            "match".to_string(),
            Value::String(format!("(?<![\\w-])({alt})(?![\\w-])")),
        );
    }

    let out = serde_json::to_string_pretty(&root).map_err(|e| e.to_string())?;
    fs::write(path, format!("{out}\n")).map_err(|e| e.to_string())?;
    Ok(())
}

fn main() -> Result<(), String> {
    let repo = repo_root();
    let ext = vscode_root(&repo);
    let schemas = ext.join("schemas");

    let docs = keyword_docs_json();
    let surface = dsl_surface_json();

    write_keyword_docs(&schemas.join("generated-keyword-docs.json"))?;
    write_json(&schemas.join("recipe.schema.json"), &recipe_schema())?;
    write_json(&schemas.join("map.schema.json"), &map_schema())?;
    write_json(&schemas.join("variables.schema.json"), &variables_schema())?;
    write_json(&schemas.join("generated-dsl-surface.json"), &surface)?;
    patch_tm_language_keys(&ext.join("syntaxes/codemod-recipe.tmLanguage.json"))?;
    write_vocabulary_md(
        &repo.join("docs/generated/dsl-vocabulary.md"),
        &docs,
        &surface,
    )?;

    eprintln!(
        "codemod_dsl_codegen: wrote schemas (recipe/map/variables), generated-dsl-surface.json, keyword-docs, TextMate, docs/generated/dsl-vocabulary.md"
    );
    Ok(())
}
