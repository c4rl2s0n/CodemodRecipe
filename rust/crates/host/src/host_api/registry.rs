use mlua::{FromLuaMulti, IntoLuaMulti, Lua, Table};
use schemars::schema::RootSchema;

use crate::host_api::context::SharedHost;

/// Static metadata for one `c:` method spec table.
#[derive(Debug, Clone, Copy)]
pub struct HostSpecInfo {
    pub name: &'static str,
    pub schema: fn() -> RootSchema,
}

/// How a host method receives its arguments.
#[derive(Debug, Clone, Copy)]
pub enum HostMethodSignature {
    /// Takes a typed spec table; the spec type carries its schema here.
    Spec(HostSpecInfo),
    /// Takes a single string id (e.g. `map`, `var`, `queryLib`).
    StringId,
    /// Takes `(cond: boolean, message?: string)`.
    Assert,
    /// Takes `(id: string, args?: { [string]: any })`.
    Run,
    /// Takes variadic values (e.g. `log(...)`).
    Variadic,
    /// Takes `(template: string, vars?: { [string]: string })`.
    Resolve,
    /// Takes `(id: string)` and returns a component delegate table.
    Component,
}

/// Declared return type for a host method.
#[derive(Debug, Clone, Copy)]
pub enum HostReturnType {
    Nil,
    String,
    Boolean,
    Integer,
    /// `{ [string]: string }` (e.g. `map`, `var`).
    StringMap,
    /// Array of strings `{ string }` (e.g. `listFiles`).
    StringList,
    /// Named type whose schema comes from [`HostSpecInfo`].
    Named(HostSpecInfo),
    /// Array of named type: `{ TypeName }`.
    NamedArray(HostSpecInfo),
    /// Component delegate with `parse` / `verify` / `readSource`.
    ComponentDelegate,
}

/// Static metadata for one `c:` method. Entries are generated by the
/// `#[host_method]` macro in `handlers.rs`.
#[derive(Debug, Clone, Copy)]
pub struct HostMethodSurface {
    pub name: &'static str,
    pub description: &'static str,
    pub signature: HostMethodSignature,
    pub return_type: HostReturnType,
    /// For methods that accept either a string or a `{ path: string }` table
    /// (currently only `read`).
    pub accept_string: bool,
}

/// One runtime host method: surface metadata plus a registration function that
/// binds the handler onto the `c` table.
#[derive(Debug, Clone, Copy)]
pub(crate) struct HostMethod {
    #[allow(dead_code)]
    pub surface: &'static HostMethodSurface,
    pub register: fn(&Lua, &Table, &SharedHost) -> Result<(), String>,
}

pub(crate) fn set_fn<F, A, R>(lua: &Lua, ctx: &Table, name: &str, f: F) -> Result<(), String>
where
    F: Fn(&Lua, A) -> Result<R, mlua::Error> + 'static,
    A: FromLuaMulti,
    R: IntoLuaMulti,
{
    let fun = lua.create_function(f).map_err(|e| e.to_string())?;
    ctx.set(name, fun).map_err(|e| e.to_string())
}

pub(crate) fn rt(msg: String) -> mlua::Error {
    mlua::Error::RuntimeError(msg)
}

/// Distributed slice collecting the surface metadata for every `c:` method.
/// Populated by `#[host_method]` in `handlers.rs` and a few manual entries
/// (`resolve`, `component`).
///
/// # Safety / `unsafe_code` allow
///
/// [`linkme`](https://docs.rs/linkme) is a **safe API** (you do not write
/// `unsafe`; only `'static` linker-gathered data). Its `#[distributed_slice]`
/// proc-macro still **expands into this crate** as `unsafe extern`,
/// `#[unsafe(link_section)]`, and `unsafe { … }` helpers. Workspace
/// `unsafe_code = deny` therefore requires this scoped allow — the lint does
/// not exempt trusted-macro expansions. Canonical rationale for all host API
/// linkme sites.
// SAFETY: allow is only for linkme's expansion; entries are `'static` metadata.
#[allow(unsafe_code)]
#[::linkme::distributed_slice]
pub static HOST_API_SURFACE: [HostMethodSurface] = [..];

/// Distributed slice collecting the runtime registration closures for every
/// `c:` method except those registered manually in `lua_runtime.rs` /
/// `component/delegate.rs` (`run`, `log`, `resolve`, `component`) because they
/// need recursive `build_ctx` or non-spec signatures.
///
/// See [`HOST_API_SURFACE`] for why `#[allow(unsafe_code)]` is required.
// SAFETY: allow is only for linkme's expansion; entries are `'static` metadata.
#[allow(unsafe_code)]
#[::linkme::distributed_slice]
pub(crate) static HOST_METHODS: [HostMethod] = [..];

#[cfg(test)]
mod tests {
    use std::collections::HashSet;

    use super::*;

    #[test]
    fn surface_has_all_expected_methods() {
        let names: Vec<_> = HOST_API_SURFACE.iter().map(|m| m.name).collect();
        for expected in [
            "insert",
            "replace",
            "remove",
            "create",
            "delete",
            "read",
            "spanText",
            "query",
            "queryMatches",
            "queryExists",
            "queryCount",
            "expectMatch",
            "expectNoMatch",
            "postExec",
            "template",
            "log",
            "run",
            "map",
            "var",
            "queryLib",
            "listFiles",
            "matchFiles",
            "filename",
            "assert",
            "resolve",
            "component",
        ] {
            assert!(names.contains(&expected), "missing {expected}");
        }
    }

    #[test]
    fn methods_and_surface_are_consistent() {
        let surface_names: HashSet<_> = HOST_API_SURFACE.iter().map(|m| m.name).collect();
        let method_names: HashSet<_> = HOST_METHODS.iter().map(|m| m.surface.name).collect();

        assert!(
            surface_names.contains("run"),
            "run must be present in the surface metadata"
        );
        assert!(
            surface_names.contains("log"),
            "log must be present in the surface metadata"
        );
        assert!(
            !method_names.contains("run"),
            "run must be registered manually, not via HOST_METHODS"
        );
        assert!(
            !method_names.contains("log"),
            "log must be registered manually, not via HOST_METHODS"
        );
        assert!(
            !method_names.contains("resolve"),
            "resolve must be registered manually, not via HOST_METHODS"
        );
        assert!(
            !method_names.contains("component"),
            "component must be registered manually, not via HOST_METHODS"
        );

        for name in surface_names.iter() {
            if *name == "run" || *name == "log" || *name == "resolve" || *name == "component" {
                continue;
            }
            assert!(
                method_names.contains(name),
                "HOST_METHODS missing runtime registration for {name}"
            );
        }

        for name in method_names.iter() {
            assert!(
                surface_names.contains(name),
                "HOST_METHODS has registration for unknown surface method {name}"
            );
        }
    }

    #[test]
    fn spec_methods_have_schemas() {
        for method in HOST_API_SURFACE.iter() {
            if let HostMethodSignature::Spec(info) = method.signature {
                let schema = (info.schema)();
                assert!(
                    schema.schema.object.is_some(),
                    "{} schema must describe an object",
                    method.name
                );
            }
        }
    }
}
