use std::collections::{BTreeMap, BTreeSet};
use std::path::PathBuf;

use schemars::schema::{InstanceType, RootSchema, Schema, SchemaObject, SingleOrVec};

use codemod_recipe_host::host_api::registry::{
    HostMethodSignature, HostMethodSurface, HostReturnType, HOST_API_SURFACE,
};
use codemod_recipe_lua::input_kind::{
    BUILTIN_BOOL, BUILTIN_CHOICE, BUILTIN_DIRECTORY, BUILTIN_FILE, BUILTIN_TEXT,
};
use codemod_recipe_lua::model::{Arg, Recipe};

fn main() {
    let manifest = std::env::var("CARGO_MANIFEST_DIR").expect("CARGO_MANIFEST_DIR");
    let project_root = PathBuf::from(manifest)
        .parent()
        .expect("workspace")
        .parent()
        .expect("workspace")
        .parent()
        .expect("project root")
        .to_path_buf();

    let dluau = generate_dluau();
    let ts = generate_ts();

    let dluau_path = project_root.join("vscode_extension/stubs/codemod-context.d.luau");
    let ts_path = project_root.join("vscode_extension/src/extension/language/hostApiSurface.ts");

    std::fs::write(&dluau_path, dluau).expect("write codemod-context.d.luau");
    std::fs::write(&ts_path, ts).expect("write hostApiSurface.ts");

    println!("Generated {dluau_path:?}");
    println!("Generated {ts_path:?}");
}

/// Methods sorted by name so generated output is deterministic regardless of
/// distributed-slice link order.
fn sorted_methods() -> Vec<&'static HostMethodSurface> {
    let mut methods: Vec<_> = HOST_API_SURFACE.iter().collect();
    methods.sort_by_key(|m| m.name);
    methods
}

fn collect_specs_and_definitions() -> (BTreeMap<String, RootSchema>, schemars::Map<String, Schema>)
{
    let mut spec_types: BTreeMap<String, RootSchema> = BTreeMap::new();
    let mut all_definitions: schemars::Map<String, Schema> = schemars::Map::new();
    for method in HOST_API_SURFACE.iter() {
        if let HostMethodSignature::Spec(info) = method.signature {
            let schema = (info.schema)();
            for (k, v) in schema.definitions.iter() {
                all_definitions
                    .entry(k.clone())
                    .or_insert_with(|| v.clone());
            }
            spec_types.insert(info.name.to_string(), schema);
        }
    }
    (spec_types, all_definitions)
}

fn collect_definitions() -> schemars::Map<String, Schema> {
    let mut all_definitions: schemars::Map<String, Schema> = schemars::Map::new();
    for method in HOST_API_SURFACE.iter() {
        if let HostMethodSignature::Spec(info) = method.signature {
            let schema = (info.schema)();
            for (k, v) in schema.definitions.iter() {
                all_definitions
                    .entry(k.clone())
                    .or_insert_with(|| v.clone());
            }
        }
    }
    all_definitions
}

// --- Luau generation ---

fn generate_dluau() -> String {
    let mut out = String::new();
    out.push_str("--!strict\n");
    out.push_str("-- Codemod recipe host context stubs for luau-lsp / editor IntelliSense.\n");
    out.push_str("-- Generated by rust/crates/host/src/bin/generate_host_api_surface.rs.\n");
    out.push_str("-- Do not edit manually; run `scripts/generate-host-api-surface.sh`.\n");
    out.push('\n');

    let (spec_types, all_definitions) = collect_specs_and_definitions();
    let mut emitted: BTreeSet<String> = BTreeSet::new();

    for (type_name, schema) in spec_types.iter() {
        if *type_name == "ReadSpec" {
            // `read` uses an inline union signature.
            continue;
        }
        if !emitted.insert(type_name.clone()) {
            continue;
        }
        let body = schema_object_to_luau(&schema.schema, &all_definitions, 0);
        out.push_str(&format!("export type {type_name} = {body}\n\n"));
    }

    // Emit any nested definition types (e.g. Env, Anchor, QuerySpec) that are
    // not already emitted as a spec type.
    let mut def_names: Vec<_> = all_definitions.keys().cloned().collect();
    def_names.sort();
    for name in def_names {
        let def_schema = all_definitions.get(&name).expect("present");
        if !emitted.insert(name.clone()) {
            continue;
        }
        let body = schema_to_luau(def_schema, &all_definitions, 0);
        out.push_str(&format!("export type {name} = {body}\n\n"));
    }

    // QuerySpan is not derived from a Rust spec; it is the runtime return shape.
    out.push_str("export type QuerySpan = {\n");
    out.push_str("\tstart: number,\n");
    out.push_str("\t[\"end\"]: number,\n");
    out.push_str("\ttext: string,\n");
    out.push_str("}\n\n");

    out.push_str("export type CodemodContext = {\n");
    out.push_str("\targs: { [string]: any },\n");

    for method in sorted_methods() {
        let sig = method_signature_luau(method);
        out.push_str(&format!("\t{}: {},\n", method.name, sig));
    }

    out.push_str("}\n\n");
    out.push_str("return {}\n");
    out
}

fn schema_object_to_luau(
    obj: &SchemaObject,
    definitions: &schemars::Map<String, Schema>,
    indent: usize,
) -> String {
    if let Some(reference) = &obj.reference {
        let name = reference.trim_start_matches("#/definitions/");
        return name.to_string();
    }

    if let Some(enum_values) = &obj.enum_values {
        let literals: Vec<String> = enum_values
            .iter()
            .filter_map(|v| v.as_str().map(|s| format!("\"{s}\"")))
            .collect();
        if !literals.is_empty() {
            return literals.join(" | ");
        }
    }

    if let Some(subschemas) = &obj.subschemas {
        let mut parts = Vec::new();
        if let Some(any_of) = &subschemas.any_of {
            for s in any_of {
                parts.push(schema_to_luau(s, definitions, indent));
            }
        }
        if let Some(one_of) = &subschemas.one_of {
            for s in one_of {
                parts.push(schema_to_luau(s, definitions, indent));
            }
        }
        if let Some(all_of) = &subschemas.all_of {
            for s in all_of {
                parts.push(schema_to_luau(s, definitions, indent));
            }
        }
        if !parts.is_empty() {
            return collapse_null_union(parts);
        }
    }

    match obj.instance_type.as_ref() {
        Some(SingleOrVec::Single(ty)) => match **ty {
            InstanceType::Null => "nil".to_string(),
            InstanceType::Boolean => "boolean".to_string(),
            InstanceType::Object => object_schema_to_luau(obj, definitions, indent),
            InstanceType::Array => array_schema_to_luau(obj, definitions, indent),
            InstanceType::Number | InstanceType::Integer => "number".to_string(),
            InstanceType::String => "string".to_string(),
        },
        Some(SingleOrVec::Vec(types)) => {
            let parts: Vec<String> = types.iter().map(instance_type_to_luau).collect();
            collapse_null_union(parts)
        }
        None => "any".to_string(),
    }
}

fn instance_type_to_luau(ty: &InstanceType) -> String {
    match ty {
        InstanceType::Null => "nil".to_string(),
        InstanceType::Boolean => "boolean".to_string(),
        InstanceType::Object => "any".to_string(),
        InstanceType::Array => "any".to_string(),
        InstanceType::Number | InstanceType::Integer => "number".to_string(),
        InstanceType::String => "string".to_string(),
    }
}

fn collapse_null_union(parts: Vec<String>) -> String {
    let non_null: Vec<String> = parts.into_iter().filter(|p| p != "nil").collect();
    if non_null.is_empty() {
        "nil".to_string()
    } else if non_null.len() == 1 {
        non_null.into_iter().next().unwrap()
    } else {
        non_null.join(" | ")
    }
}

fn object_schema_to_luau(
    obj: &SchemaObject,
    definitions: &schemars::Map<String, Schema>,
    indent: usize,
) -> String {
    if let Some(additional) = obj
        .object
        .as_ref()
        .and_then(|o| o.additional_properties.as_ref())
    {
        let empty_props = obj
            .object
            .as_ref()
            .map(|o| o.properties.is_empty())
            .unwrap_or(true);
        if empty_props {
            return match additional.as_ref() {
                Schema::Bool(true) => "{ [string]: any }".to_string(),
                Schema::Bool(false) => "{}".to_string(),
                Schema::Object(_) => {
                    let value = schema_to_luau(additional, definitions, indent + 1);
                    format!("{{ [string]: {value} }}")
                }
            };
        }
    }

    let required: BTreeSet<String> = obj
        .object
        .as_ref()
        .map(|o| o.required.iter().cloned().collect())
        .unwrap_or_default();

    let props = obj
        .object
        .as_ref()
        .map(|o| o.properties.clone())
        .unwrap_or_default();

    let mut lines = Vec::new();
    let mut prop_keys: Vec<_> = props.keys().cloned().collect();
    prop_keys.sort();
    for key in prop_keys {
        let prop = props.get(&key).expect("present");
        let optional = !required.contains(&key);
        let value = schema_to_luau(prop, definitions, indent + 1);
        let suffix = if optional { "?" } else { "" };
        let key_str = if is_valid_luau_identifier(&key) {
            key.clone()
        } else {
            format!("[\"{key}\"]")
        };
        lines.push(format!("\t{}{suffix}: {value},", key_str));
    }

    if lines.is_empty() {
        return "{}".to_string();
    }

    let body = lines.join("\n");
    format!("{{\n{}\n}}", body)
}

fn array_schema_to_luau(
    obj: &SchemaObject,
    definitions: &schemars::Map<String, Schema>,
    _indent: usize,
) -> String {
    let items = obj
        .array
        .as_ref()
        .and_then(|a| a.items.as_ref())
        .map(|items| match items {
            SingleOrVec::Single(schema) => schema_to_luau(schema, definitions, 0),
            SingleOrVec::Vec(_) => "any".to_string(),
        })
        .unwrap_or_else(|| "any".to_string());
    format!("{{ [number]: {items} }}")
}

fn schema_to_luau(
    schema: &Schema,
    definitions: &schemars::Map<String, Schema>,
    indent: usize,
) -> String {
    match schema {
        Schema::Bool(true) => "any".to_string(),
        Schema::Bool(false) => "never".to_string(),
        Schema::Object(obj) => schema_object_to_luau(obj, definitions, indent),
    }
}

fn is_valid_luau_identifier(s: &str) -> bool {
    let mut chars = s.chars();
    let first = chars.next().unwrap_or('_');
    first.is_alphabetic() && s.chars().all(|c| c.is_alphanumeric() || c == '_')
}

fn method_signature_luau(method: &HostMethodSurface) -> String {
    let ret = return_type_luau(method.return_type);
    match method.signature {
        HostMethodSignature::Spec(ref info) => {
            if method.accept_string {
                return format!(
                    "(self: CodemodContext, path: string | {{ path: string }}) -> {ret}"
                );
            }
            let type_name = info.name;
            format!("(self: CodemodContext, spec: {type_name}) -> {ret}")
        }
        HostMethodSignature::StringId => match method.return_type {
            HostReturnType::String => format!("(self: CodemodContext, id: string) -> {ret}"),
            _ => "(self: CodemodContext, id: string) -> { [string]: string }".to_string(),
        },
        HostMethodSignature::Assert => {
            "(self: CodemodContext, cond: boolean, msg: string?) -> ()".to_string()
        }
        HostMethodSignature::Run => {
            "(self: CodemodContext, id: string, args: { [string]: any }?) -> ()".to_string()
        }
    }
}

fn return_type_luau(ret: HostReturnType) -> &'static str {
    match ret {
        HostReturnType::Nil => "()",
        HostReturnType::String => "string",
        HostReturnType::Boolean => "boolean",
        HostReturnType::Integer => "number",
        HostReturnType::Table => "{ [string]: string }",
        HostReturnType::QuerySpans => "{ QuerySpan }",
    }
}

// --- TypeScript generation ---

fn generate_ts() -> String {
    let mut out = String::new();
    out.push_str("/**\n");
    out.push_str(" * Static Luau host API surface for recipe editor completions / hover.\n");
    out.push_str(" * Generated by rust/crates/host/src/bin/generate_host_api_surface.rs.\n");
    out.push_str(" * Do not edit manually; run `scripts/generate-host-api-surface.sh`.\n");
    out.push_str(" */\n\n");

    out.push_str("export type HostMethodSpec = {\n");
    out.push_str("  name: string;\n");
    out.push_str("  description: string;\n");
    out.push_str(
        "  /** Spec-table keys when the method takes `{ ... }` (empty for string-only). */\n",
    );
    out.push_str("  keys: string[];\n");
    out.push_str("  /** Keys that accept enum values. */\n");
    out.push_str("  enums?: Record<string, string[]>;\n");
    out.push_str("};\n\n");

    out.push_str("export const HOST_CONTEXT_FIELD = 'args';\n\n");

    let all_definitions = collect_definitions();
    let methods = sorted_methods();

    let mut method_bodies = Vec::new();
    for method in &methods {
        let (keys, enums) = method_keys_and_enums(method, &all_definitions);
        let keys_str = keys
            .iter()
            .map(|k| format!("'{k}'"))
            .collect::<Vec<_>>()
            .join(", ");
        let mut body = String::new();
        body.push_str(&format!("  {{\n    name: '{}',\n", method.name));
        body.push_str(&format!(
            "    description: '{}',\n",
            escape_js_string(method.description)
        ));
        body.push_str(&format!("    keys: [{}],\n", keys_str));
        if let Some(enums) = enums {
            body.push_str("    enums: {\n");
            let mut enum_keys: Vec<_> = enums.keys().cloned().collect();
            enum_keys.sort();
            for k in enum_keys {
                let vals = &enums[&k];
                let vals_str = vals
                    .iter()
                    .map(|v| format!("'{v}'"))
                    .collect::<Vec<_>>()
                    .join(", ");
                body.push_str(&format!("      {k}: [{vals_str}],\n"));
            }
            body.push_str("    },\n");
        }
        body.push_str("  }");
        method_bodies.push(body);
    }

    out.push_str("export const HOST_METHODS: readonly HostMethodSpec[] = [\n");
    out.push_str(&method_bodies.join(",\n"));
    out.push_str("\n];\n\n");

    let mut recipe_keys = object_keys_from_schema(&schemars::schema_for!(Recipe));
    if let Some(pos) = recipe_keys.iter().position(|k| k == "args") {
        recipe_keys.insert(pos + 1, "apply".to_string());
    } else {
        recipe_keys.push("apply".to_string());
    }

    out.push_str("export const RECIPE_MODULE_KEYS: readonly string[] = [\n");
    for k in &recipe_keys {
        out.push_str(&format!("  '{}',\n", snake_to_camel(k)));
    }
    out.push_str("];\n\n");

    out.push_str("export const RECIPE_MODULE_DOCS: Record<string, string> = {\n");
    for (k, doc) in recipe_module_docs() {
        out.push_str(&format!("  {}: '{}',\n", k, escape_js_string(doc)));
    }
    out.push_str("};\n\n");

    let arg_keys = object_keys_from_schema(&schemars::schema_for!(Arg));

    out.push_str("export const ARG_DEFINITION_KEYS: readonly string[] = [\n");
    for k in &arg_keys {
        out.push_str(&format!("  '{}',\n", snake_to_camel(k)));
    }
    out.push_str("];\n\n");

    out.push_str("export const ARG_DEFINITION_DOCS: Record<string, string> = {\n");
    for (k, doc) in arg_definition_docs() {
        out.push_str(&format!("  {}: '{}',\n", k, escape_js_string(doc)));
    }
    out.push_str("};\n\n");

    out.push_str("export const BUILTIN_INPUT_KINDS: readonly string[] = [\n");
    for k in [
        BUILTIN_TEXT,
        BUILTIN_BOOL,
        BUILTIN_CHOICE,
        BUILTIN_FILE,
        BUILTIN_DIRECTORY,
    ] {
        out.push_str(&format!("  '{k}',\n"));
    }
    out.push_str("];\n\n");

    out.push_str("export const HOST_METHOD_DOCS: Record<string, string> = Object.fromEntries(\n");
    out.push_str("  HOST_METHODS.map((m) => [m.name, m.description])\n");
    out.push_str(");\n\n");

    out.push_str("export function hostMethodByName(name: string): HostMethodSpec | undefined {\n");
    out.push_str("  return HOST_METHODS.find((m) => m.name === name);\n");
    out.push_str("}\n");

    out
}

fn method_keys_and_enums(
    method: &HostMethodSurface,
    definitions: &schemars::Map<String, Schema>,
) -> (Vec<String>, Option<BTreeMap<String, Vec<String>>>) {
    match method.signature {
        HostMethodSignature::Spec(ref info) => {
            let schema = (info.schema)();
            let mut keys = Vec::new();
            let mut enums: BTreeMap<String, Vec<String>> = BTreeMap::new();
            let props = schema
                .schema
                .object
                .as_ref()
                .map(|o| o.properties.clone())
                .unwrap_or_default();
            let mut prop_keys: Vec<_> = props.keys().cloned().collect();
            prop_keys.sort();
            for k in prop_keys {
                let prop = props.get(&k).expect("present");
                let key = snake_to_camel(&k);
                keys.push(key.clone());
                if let Some(values) = enum_values(prop, definitions) {
                    enums.insert(key, values);
                }
            }
            if method.accept_string {
                keys = vec!["path".to_string()];
            }
            (keys, if enums.is_empty() { None } else { Some(enums) })
        }
        HostMethodSignature::StringId | HostMethodSignature::Assert | HostMethodSignature::Run => {
            (Vec::new(), None)
        }
    }
}

fn enum_values(
    schema: &Schema,
    definitions: &schemars::Map<String, Schema>,
) -> Option<Vec<String>> {
    match schema {
        Schema::Object(obj) => {
            if let Some(reference) = &obj.reference {
                let name = reference.trim_start_matches("#/definitions/");
                return definitions
                    .get(name)
                    .and_then(|s| enum_values(s, definitions));
            }
            if let Some(values) = &obj.enum_values {
                let literals: Vec<String> = values
                    .iter()
                    .filter_map(|v| v.as_str().map(|s| s.to_string()))
                    .collect();
                if !literals.is_empty() {
                    return Some(literals);
                }
            }
            if let Some(subschemas) = &obj.subschemas {
                let mut parts = Vec::new();
                if let Some(any_of) = &subschemas.any_of {
                    parts.extend(any_of);
                }
                if let Some(one_of) = &subschemas.one_of {
                    parts.extend(one_of);
                }
                let non_null: Vec<&Schema> =
                    parts.into_iter().filter(|s| !is_null_schema(s)).collect();
                if non_null.len() == 1 {
                    return enum_values(non_null[0], definitions);
                }
            }
            None
        }
        _ => None,
    }
}

fn is_null_schema(schema: &Schema) -> bool {
    if let Schema::Object(obj) = schema {
        if let Some(SingleOrVec::Single(ty)) = obj.instance_type.as_ref() {
            return **ty == InstanceType::Null;
        }
    }
    false
}

fn object_keys_from_schema(root: &RootSchema) -> Vec<String> {
    root.schema
        .object
        .as_ref()
        .map(|o| o.properties.keys().cloned().collect())
        .unwrap_or_default()
}

fn snake_to_camel(s: &str) -> String {
    let mut out = String::new();
    let mut upper = false;
    for ch in s.chars() {
        if ch == '_' {
            upper = true;
        } else if upper {
            out.push(ch.to_ascii_uppercase());
            upper = false;
        } else {
            out.push(ch);
        }
    }
    out
}

fn escape_js_string(s: &str) -> String {
    s.replace('\\', "\\\\")
        .replace('\'', "\\'")
        .replace('\n', "\\n")
}

